CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS titles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  min_kg integer NOT NULL,
  max_kg integer,
  description text NOT NULL
);

ALTER TABLE titles
  ALTER COLUMN max_kg DROP NOT NULL;

CREATE TABLE IF NOT EXISTS categories (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  parent_id integer REFERENCES categories(id),
  sort_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  UNIQUE (parent_id, name)
);

CREATE TABLE IF NOT EXISTS users (
  id text PRIMARY KEY,
  nickname text NOT NULL,
  profile_image text,
  trust_score integer NOT NULL DEFAULT 50,
  kg_score integer NOT NULL DEFAULT 0,
  role text NOT NULL DEFAULT 'user',
  title_id integer REFERENCES titles(id),
  preferred_categories integer[] NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS role text NOT NULL DEFAULT 'user';

CREATE TABLE IF NOT EXISTS restaurants (
  id text PRIMARY KEY,
  name text NOT NULL,
  category_id integer NOT NULL REFERENCES categories(id),
  address text NOT NULL,
  phone text,
  price_range text,
  business_hours text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS posts (
  id text PRIMARY KEY,
  user_id text NOT NULL REFERENCES users(id),
  restaurant_id text NOT NULL REFERENCES restaurants(id),
  category_id integer NOT NULL REFERENCES categories(id),
  title text NOT NULL,
  content text NOT NULL,
  average_rating numeric(2, 1) NOT NULL DEFAULT 0,
  review_count integer NOT NULL DEFAULT 0,
  photo_count integer NOT NULL DEFAULT 0,
  like_count integer NOT NULL DEFAULT 0,
  kg_score integer NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'published',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  photos text[] NOT NULL DEFAULT '{}'
);

CREATE TABLE IF NOT EXISTS reviews (
  id text PRIMARY KEY,
  post_id text NOT NULL REFERENCES posts(id),
  user_id text NOT NULL REFERENCES users(id),
  rating integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
  content text NOT NULL,
  photos text[] NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS post_likes (
  user_id text NOT NULL REFERENCES users(id),
  post_id text NOT NULL REFERENCES posts(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, post_id)
);

CREATE TABLE IF NOT EXISTS post_scraps (
  user_id text NOT NULL REFERENCES users(id),
  post_id text NOT NULL REFERENCES posts(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, post_id)
);

CREATE TABLE IF NOT EXISTS auth_accounts (
  id text PRIMARY KEY,
  user_id text NOT NULL REFERENCES users(id),
  provider text NOT NULL,
  provider_user_id text NOT NULL,
  email text,
  access_token_enc text NOT NULL DEFAULT '',
  refresh_token_enc text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (provider, provider_user_id)
);

CREATE TABLE IF NOT EXISTS ai_recommendation_logs (
  id text PRIMARY KEY,
  user_id text NOT NULL REFERENCES users(id),
  request_context jsonb NOT NULL,
  candidate_restaurant_ids text[] NOT NULL DEFAULT '{}',
  final_recommendation jsonb NOT NULL,
  model_name text NOT NULL,
  prompt_version text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

