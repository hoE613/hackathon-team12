    ('user_demo_02', 'auth_demo_02', 'demo-user-02', '데모유저2', 'demo2@example.com', ARRAY['중식', '술집']::text[]),
    ('user_demo_03', 'auth_demo_03', 'demo-user-03', '데모유저3', 'demo3@example.com', ARRAY['일식', '중식']::text[]),
    ('user_demo_04', 'auth_demo_04', 'demo-user-04', '데모유저4', 'demo4@example.com', ARRAY['술집', '양식']::text[]),
    ('user_demo_05', 'auth_demo_05', 'demo-user-05', '데모유저5', 'demo5@example.com', ARRAY['양식', '중식']::text[])
),
prepared_accounts AS (
  SELECT
    account.user_id,
    account.auth_id,
    account.code,
    account.nickname,
    account.email,
    COALESCE(array_agg(category.id ORDER BY array_position(account.preferred_category_names, category.name)) FILTER (WHERE category.id IS NOT NULL), '{}') AS preferred_category_ids
  FROM development_accounts account
  LEFT JOIN categories category ON category.name = ANY(account.preferred_category_names)
  GROUP BY account.user_id, account.auth_id, account.code, account.nickname, account.email, account.preferred_category_names
),
upserted_users AS (
  INSERT INTO users (id, nickname, profile_image, trust_score, kg_score, role, title_id, preferred_categories)
  SELECT
    user_id,
    nickname,
    NULL,
    50,
    0,
    'user',
    (SELECT id FROM titles WHERE name = '입문자' LIMIT 1),
    preferred_category_ids::integer[]
  FROM prepared_accounts
  ON CONFLICT (id) DO UPDATE SET
    nickname = EXCLUDED.nickname,
    role = EXCLUDED.role,
    title_id = COALESCE(users.title_id, EXCLUDED.title_id),
    preferred_categories = EXCLUDED.preferred_categories
  RETURNING id
)
